class ChecksSpecError(ValueError):
    """The spec file is missing, malformed or names a file that does not exist."""


@dataclasses.dataclass(frozen=True)
class StackSpec:
    """What the spec gives the repositories that hold one stack."""

    name: str
    files: dict[str, Path]
    pre_commit: Path | None
    pyproject_tables: tuple[tuple[str, ...], ...]
    setup_cfg_sections: tuple[str, ...]
    remove_files: tuple[str, ...]
    hook_files: dict[str, tuple[str, ...]]
    tsconfig_base: str | None
    eslint_imports: tuple[str, ...]
    node_dev_dependencies: tuple[str, ...]


@dataclasses.dataclass(frozen=True)
class ChecksSpec:
    """The parsed spec file."""

    source: Path
    pins: dict[str, object]
    common_pre_commit: Path
    stacks: dict[str, StackSpec]
    supersede_repos: frozenset[str]
    supersede_tools: frozenset[str]
    lint_task: str
    pre_commit_pin: str


@dataclasses.dataclass(frozen=True)
class FileChange:
    """One path whose text differs from what the spec wants; `wanted` None removes the file.

    `hook` marks the commit hook git runs from the tree (a `core.hooksPath` folder inside it).
    """

    path: str
    current: str | None
    wanted: str | None
    executable: bool = False
    hook: bool = False


@dataclasses.dataclass(frozen=True)
class RepoPlan:
    """Everything checks-sync would do in one repository, and what it cannot do itself."""

    stacks: tuple[str, ...]
    unchecked: tuple[str, ...]
    changes: tuple[FileChange, ...]
    notes: tuple[str, ...]
    install_pre_commit: bool

    @property
    def state(self) -> str:
        """Name the repository's state.

        Returns:
            `missing` (never synced), `outdated` (files differ), `unconsumed` (files current but a
            repository file does not use them, or the commit hook is not installed) or `current`.

        """
        if any(change.path == CHECKS_JSON and change.current is None for change in self.changes):
            return "missing"
        if self.changes:
            return "outdated"
        if self.notes or self.install_pre_commit:
            return "unconsumed"
        return "current"


