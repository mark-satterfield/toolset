def _without_tables(text: str, tables: Sequence[tuple[str, ...]]) -> str:
    """Remove tables from a TOML document, keeping every other table and comment.

    Args:
        text: The document.
        tables: Dotted table paths, for example ("tool", "ruff").

    Returns:
        The document, unchanged when it holds none of the tables or does not parse.

    """
    try:
        document = tomlkit.parse(text)
    except TOMLKitError:
        return text
    removed = [path for path in tables if _delete_table(document, path)]
    if not removed:
        return text
    return tomlkit.dumps(document).rstrip("\n") + "\n"


def _delete_table(document: MutableMapping[str, object], path: tuple[str, ...]) -> bool:
    """Delete one table and, when that empties it, its parent.

    Args:
        document: The document or table holding the path.
        path: The table's dotted path below it.

    Returns:
        True when the table existed.

    """
    head, *rest = path
    child: object = document.get(head)
    if not rest:
        if child is None:
            return False
        del document[head]
        return True
    if not isinstance(child, MutableMapping) or not _delete_table(child, tuple(rest)):
        return False
    if not child:
        del document[head]
    return True


def _without_sections(text: str, patterns: Sequence[str]) -> str:
    """Remove INI sections whose names match a pattern, keeping every other line.

    Args:
        text: The file.
        patterns: fnmatch patterns of section names.

    Returns:
        The file without those sections.

    """
    kept: list[str] = []
    dropping = False
    for line in text.splitlines(keepends=True):
        header = SECTION_HEADER.match(line)
        dropping = any(fnmatch.fnmatchcase(header.group(1).strip(), p) for p in patterns) if header else dropping
        kept.extend([] if dropping else [line])
    return "".join(kept)


def _lint_task_text(text: str, lint_task: str) -> str:
    """Set the Taskfile's `lint` task to run the runner, keeping every other task.

    Args:
        text: The Taskfile.
        lint_task: The command the task runs.

    Returns:
        The Taskfile, unchanged when it does not parse as a Taskfile.

    """
    yaml = _round_trip_yaml()
    try:
        document: object = yaml.load(text)
    except YAMLError:
        return text
    tasks: object = document.get("tasks") if isinstance(document, CommentedMap) else None
    if not isinstance(tasks, CommentedMap):
        return text
    lint: object = tasks.get("lint")
    if not isinstance(lint, CommentedMap):
        lint = CommentedMap()
        tasks["lint"] = lint
    commands: object = lint.get("cmds")
    if isinstance(commands, CommentedSeq) and list(commands) == [lint_task] and lint.get("desc") is not None:
        return text
    lint["desc"] = LINT_TASK_DESCRIPTION
    if isinstance(commands, CommentedSeq) and commands:
        del commands[1:]
        commands[0] = lint_task
    else:
        lint["cmds"] = CommentedSeq([lint_task])
    buffer = io.StringIO()
    yaml.dump(document, buffer)
    return buffer.getvalue()


def _json_flat(value: object) -> str | None:
    """Render a JSON value on one line when Prettier would keep it on one line regardless of width.

    Args:
        value: A parsed JSON value.

    Returns:
        A scalar or empty container as text, None for a non-empty object or array.

    """
    if isinstance(value, dict | list):
        return None if value else json.dumps(value)
    return json.dumps(value, ensure_ascii=False)


def _json_flat_array(items: Sequence[object]) -> str | None:
    """Render an array on one line when every item is a scalar or an empty container.

    Args:
        items: The array's items.

    Returns:
        The one-line array, or None when an item needs lines of its own.

    """
    parts: list[str | None] = [_json_flat(item) for item in items]
    flat_parts: list[str] = [part for part in parts if part is not None]
    return f"[{', '.join(flat_parts)}]" if len(flat_parts) == len(parts) else None


def _json_one_line(value: object, head: str, tail: str) -> str | None:
    """Render a value on its line when it fits there as Prettier fits it.

    Args:
        value: A parsed JSON value.
        head: The text before the value on its line (indent and key).
        tail: The text after it (a comma or nothing).

    Returns:
        The whole line, or None when the value breaks over several lines.

    """
    if not isinstance(value, list):
        flat = _json_flat(value)
        return None if flat is None else f"{head}{flat}{tail}"
    flat_array = _json_flat_array(value)
    if flat_array is None or len(head) + len(flat_array) + len(tail) > JSON_PRINT_WIDTH:
        return None
    return f"{head}{flat_array}{tail}"


def _json_lines(value: object, depth: int, head: str, tail: str) -> list[str]:
    """Render a JSON value as the lines Prettier formats it into.

    A non-empty object is always expanded; an array stays on one line when its items are all
    scalars and the line fits the print width.

    Args:
        value: A parsed JSON value.
        depth: Its nesting depth.
        head: The text before it on its first line.
        tail: The text after it on its last line.

    Returns:
        The lines.

    """
    one_line = _json_one_line(value, head, tail)
    if one_line is not None:
        return [one_line]
    inner = JSON_INDENT * (depth + 1)
    entries: list[tuple[str, object]] = (
        [(inner, item) for item in value]
        if isinstance(value, list)
        else [(f"{inner}{json.dumps(str(key), ensure_ascii=False)}: ", item) for key, item in _json_items(value)]
    )
    opener, closer = ("[", "]") if isinstance(value, list) else ("{", "}")
    last = len(entries) - 1
    body = [
        line
        for index, (prefix, item) in enumerate(entries)
        for line in _json_lines(item, depth + 1, prefix, "" if index == last else ",")
    ]
    return [f"{head}{opener}", *body, f"{JSON_INDENT * depth}{closer}{tail}"]


def _json_items(value: object) -> list[tuple[object, object]]:
    """List an object's members.

    Args:
        value: A parsed JSON object.

    Returns:
        Its key and value pairs.

    Raises:
        TypeError: When the value is not an object.

    """
    if not isinstance(value, dict):
        message = f"expected a JSON object, got {type(value).__name__}"
        raise TypeError(message)
    return list(value.items())


def json_text(value: object) -> str:
    """Write a JSON value as Prettier formats it under the canonical .prettierrc.json.

    Args:
        value: A JSON-serialisable value.

    Returns:
        The text, newline-terminated.

    """
    return "\n".join(_json_lines(value, 0, "", "")) + "\n"


def _single_quoted(node: object) -> object:
    """Single-quote every double-quoted YAML value Prettier would single-quote, in place.

    The canonical .prettierrc.json sets `singleQuote` for YAML; a value holding a single quote
    or a backslash, or a character that is not printable, keeps its double quotes.

    Args:
        node: A loaded YAML node.

    Returns:
        The node, with its double-quoted values replaced.

    """
    if isinstance(node, DoubleQuotedScalarString) and node.isprintable() and not NOT_SINGLE_QUOTABLE & set(node):
        return SingleQuotedScalarString(str(node))
    if isinstance(node, CommentedMap):
        node.update({key: _single_quoted(value) for key, value in node.items()})
    if isinstance(node, CommentedSeq):
        node[:] = [_single_quoted(item) for item in node]
    return node


def _extends_first(text: str, base: str) -> str | None:
    """List the base first in a tsconfig's `extends`.

    Args:
        text: The tsconfig.
        base: The base file's name at the tree root.

    Returns:
        The new text, the same text when the base is already first, or None when the file is not plain JSON.

    """
    try:
        parsed: object = json.loads(text)
    except json.JSONDecodeError:
        return None
    if not isinstance(parsed, dict):
        return None
    reference = f"./{base}"
    extends: object = parsed.get("extends")
    others = [extends] if isinstance(extends, str) else (extends if isinstance(extends, list) else [])
    if others[:1] == [reference]:
        return json_text(parsed) if text == json.dumps(parsed, indent=2, ensure_ascii=False) + "\n" else text
    rest = [item for item in others if item != reference]
    parsed["extends"] = [reference, *rest] if rest else reference
    ordered = {"extends": parsed["extends"], **{key: value for key, value in parsed.items() if key != "extends"}}
    return json_text(ordered)


