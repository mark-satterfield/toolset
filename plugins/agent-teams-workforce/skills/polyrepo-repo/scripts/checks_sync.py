def _hook_section(spec: ChecksSpec) -> str:
    """Build the section a shared hooks folder's pre-commit hook gets, which runs pre-commit.

    Args:
        spec: The spec, for the pre-commit pin.

    Returns:
        The marked section.

    """
    return "\n".join([
        HOOK_BEGIN,
        "# Written by `polyrepo checks-sync`: runs the repository's pre-commit hooks on the staged files.",
        f"if [ -f {PRE_COMMIT_CONFIG} ]; then",
        "  if command -v pre-commit >/dev/null; then",
        "    pre-commit run --hook-stage pre-commit || exit $?",
        "  else",
        f"    uvx pre-commit@{spec.pre_commit_pin} run --hook-stage pre-commit || exit $?",
        "  fi",
        "fi",
        HOOK_END,
        "",
    ])


def _with_hook_section(current: str | None, spec: ChecksSpec) -> str:
    """Put the marked section into a hook script, replacing an earlier copy of it.

    Args:
        current: The hook script, or None.
        spec: The spec.

    Returns:
        The script.

    """
    text = current or HOOK_SHEBANG
    begin, end = text.find(HOOK_BEGIN), text.find(HOOK_END)
    if begin != -1 and end > begin:
        text = text[:begin] + text[end + len(HOOK_END) :].lstrip("\n")
    return text.rstrip("\n") + "\n" + _hook_section(spec)


@dataclasses.dataclass(frozen=True)
class HookPlan:
    """How the commit hook reaches pre-commit in one repository."""

    change: FileChange | None
    install: bool
    note: str | None


def plan_hook(root: Path, spec: ChecksSpec, git_output: GitOutput) -> HookPlan:
    """Plan the commit hook.

    Without `core.hooksPath`, `pre-commit install` writes the hook (it refuses when the path is
    set). With it, the marked section is added to the shared folder's pre-commit hook, after
    whatever else that hook runs; inside the tree that hook is one of the planned files.

    Args:
        root: The working tree.
        spec: The spec.
        git_output: Runs git in a folder.

    Returns:
        The plan.

    """
    hook = git_output(root, ["rev-parse", "--path-format=absolute", "--git-path", "hooks/pre-commit"])
    if hook is None:
        return HookPlan(None, install=False, note="git cannot name the pre-commit hook path")
    path = Path(hook)
    current = path.read_text(encoding="utf-8") if path.is_file() else None
    if not git_output(root, ["config", "--get", "core.hooksPath"]):
        return HookPlan(None, install=current is None or PRE_COMMIT_GENERATED not in current, note=None)
    wanted = _with_hook_section(current, spec)
    if not path.is_relative_to(root.resolve()):
        note = None if current == wanted else f"core.hooksPath hook {path} outside the tree does not run pre-commit"
        return HookPlan(None, install=False, note=note)
    rel = path.relative_to(root.resolve()).as_posix()
    change = FileChange(rel, current, wanted, executable=True, hook=True) if current != wanted else None
    return HookPlan(change, install=False, note=None)


