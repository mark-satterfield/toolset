def _fragment_repos(path: Path) -> list[CommentedMap]:
    """Read a pre-commit fragment's repo entries: a `repos:` mapping or a bare list of entries.

    Args:
        path: The fragment.

    Returns:
        The entries.

    Raises:
        ChecksSpecError: When the fragment is not shaped as pre-commit repos.

    """
    loaded: object = _round_trip_yaml().load(path.read_text(encoding="utf-8"))
    repos: object = loaded.get("repos") if isinstance(loaded, CommentedMap) else loaded
    if not isinstance(repos, list) or not all(isinstance(entry, CommentedMap) for entry in repos):
        message = f"{path}: expected a list of pre-commit repo entries"
        raise ChecksSpecError(message)
    return [entry for entry in repos if isinstance(entry, CommentedMap)]


def _hooks_of(entry: CommentedMap) -> list[CommentedMap]:
    """Return a repo entry's hooks.

    Args:
        entry: The repo entry.

    Returns:
        Its hook mappings.

    """
    hooks: object = entry.get("hooks")
    return [hook for hook in hooks if isinstance(hook, CommentedMap)] if isinstance(hooks, list) else []


def _entry_tools(hook: CommentedMap) -> frozenset[str]:
    """Name the programs a local hook's entry runs.

    Args:
        hook: The hook.

    Returns:
        The base name of every token of its entry.

    """
    entry = str(hook.get("entry") or "")
    try:
        tokens = shlex.split(entry)
    except ValueError:
        tokens = entry.split()
    return frozenset(PurePosixPath(token).name for token in tokens)


def _kept_local_hook(hook: CommentedMap, spec: ChecksSpec) -> bool:
    """Report whether a repository's local hook survives the merge.

    Args:
        hook: The hook.
        spec: The spec.

    Returns:
        False for a hook the steward owns (it runs the runner) or one a canonical hook replaces.

    """
    owned = RUNNER_MARK in str(hook.get("entry") or "")
    return not owned and not (_entry_tools(hook) & spec.supersede_tools)


def _kept_entries(repos: Iterable[CommentedMap], owned_urls: frozenset[str], spec: ChecksSpec) -> list[CommentedMap]:
    """Keep the repository's own pre-commit entries, without what the canonical entries own or replace.

    Args:
        repos: The repository's repo entries.
        owned_urls: The repo URLs of the common fragment.
        spec: The spec.

    Returns:
        The surviving entries; a local entry keeps only its surviving hooks.

    """
    foreign = [entry for entry in repos if str(entry.get("repo")) not in owned_urls | spec.supersede_repos]
    kept: list[CommentedMap] = []
    for entry in foreign:
        hooks = [hook for hook in _hooks_of(entry) if entry.get("repo") != "local" or _kept_local_hook(hook, spec)]
        if hooks:
            entry["hooks"] = CommentedSeq(hooks)
            kept.append(entry)
    return kept


def _hook_excludes(repos: Iterable[CommentedMap], owned_urls: frozenset[str]) -> dict[str, object]:
    """Collect the repository's `exclude` on each hook of the common entries, which it keeps.

    Args:
        repos: The repository's repo entries.
        owned_urls: The repo URLs of the common fragment.

    Returns:
        Hook id to its exclude pattern.

    """
    owned = [entry for entry in repos if str(entry.get("repo")) in owned_urls]
    return {str(hook.get("id")): hook["exclude"] for entry in owned for hook in _hooks_of(entry) if "exclude" in hook}


def _with_excludes(entries: Iterable[CommentedMap], excludes: Mapping[str, object]) -> list[CommentedMap]:
    """Copy the common entries and put the repository's excludes back on their hooks.

    Args:
        entries: The common fragment's entries.
        excludes: Hook id to exclude pattern.

    Returns:
        The copied entries.

    """
    copies = [copy.deepcopy(entry) for entry in entries]
    for hook in (hook for entry in copies for hook in _hooks_of(entry) if str(hook.get("id")) in excludes):
        hook["exclude"] = excludes[str(hook.get("id"))]
    return copies


def _canonical_local(stacks: Sequence[StackSpec], hook_patterns: Mapping[str, str | None]) -> list[CommentedMap]:
    """Build the one local entry holding every hook of the repository's stacks.

    Args:
        stacks: The repository's stacks, in spec order.
        hook_patterns: Hook id to the `files` pattern built for this repository; None drops the hook.

    Returns:
        The local entry, or nothing when no stack has a hook.

    """
    fragments = [stack.pre_commit for stack in stacks if stack.pre_commit is not None]
    hooks = [
        copy.deepcopy(hook)
        for fragment in fragments
        for entry in _fragment_repos(fragment)
        for hook in _hooks_of(entry)
    ]
    kept = [hook for hook in hooks if str(hook.get("id")) not in hook_patterns or hook_patterns[str(hook["id"])]]
    for hook in (hook for hook in kept if str(hook.get("id")) in hook_patterns):
        hook["files"] = hook_patterns[str(hook["id"])]
    if not kept:
        return []
    entry = CommentedMap()
    entry["repo"] = "local"
    entry["hooks"] = CommentedSeq(kept)
    return [entry]


def _top_level(common: CommentedMap, current: CommentedMap) -> CommentedMap:
    """Set the common top-level keys; the repository's own top-level keys follow them.

    A repository's own `exclude` is kept, joined with the common one.

    Args:
        common: The common fragment.
        current: The repository's file.

    Returns:
        The new top level, without `repos`.

    """
    top = CommentedMap()
    for key, value in common.items():
        if key == "repos":
            continue
        own: object = current.get(key)
        joined = key == "exclude" and isinstance(own, str) and own != value and str(value) not in own
        top[key] = f"{value}|(?:{own})" if joined else (own if key == "exclude" and isinstance(own, str) else value)
    for key, value in current.items():
        if key not in top and key != "repos":
            top[key] = value
    return top


def _leading_comments(text: str) -> str:
    """Return the comment and blank lines a file starts with.

    Args:
        text: The file's text.

    Returns:
        Those lines, newline-terminated.

    """
    lines = text.splitlines(keepends=True)
    count = next((index for index, line in enumerate(lines) if line.strip() and not line.startswith("#")), len(lines))
    return "".join(lines[:count])


def pre_commit_text(
    current_text: str | None,
    spec: ChecksSpec,
    stacks: Sequence[StackSpec],
    hook_patterns: Mapping[str, str | None],
) -> str:
    """Build the repository's `.pre-commit-config.yaml`.

    The common entries come first, then every entry and hook of the repository's own that the
    canonical hooks do not own or replace, then the one local entry of the stacks' hooks.

    Args:
        current_text: The repository's file, or None.
        spec: The spec.
        stacks: The repository's stacks, in spec order.
        hook_patterns: Hook id to its per-repository `files` pattern.

    Returns:
        The file's text.

    Raises:
        ChecksSpecError: When the repository's file is not a pre-commit mapping.

    """
    yaml = _round_trip_yaml()
    try:
        loaded: object = yaml.load(current_text) if current_text else CommentedMap()
    except YAMLError as error:
        message = f"{PRE_COMMIT_CONFIG} is not valid YAML: {error}"
        raise ChecksSpecError(message) from error
    current = loaded if isinstance(loaded, CommentedMap) else CommentedMap()
    common: object = yaml.load(spec.common_pre_commit.read_text(encoding="utf-8"))
    if not isinstance(common, CommentedMap):
        message = f"{spec.common_pre_commit}: expected a mapping"
        raise ChecksSpecError(message)
    common_entries = _fragment_repos(spec.common_pre_commit)
    owned_urls = frozenset(str(entry.get("repo")) for entry in common_entries)
    repos_value: object = current.get("repos")
    repos = [entry for entry in repos_value if isinstance(entry, CommentedMap)] if isinstance(repos_value, list) else []
    excludes = _hook_excludes(repos, owned_urls)
    document = _top_level(common, current)
    document["repos"] = CommentedSeq([
        *_with_excludes(common_entries, excludes),
        *_kept_entries(repos, owned_urls, spec),
        *_canonical_local(stacks, hook_patterns),
    ])
    buffer = io.StringIO()
    yaml.dump(_single_quoted(document), buffer)
    return _leading_comments(current_text or "") + buffer.getvalue()


def hook_patterns(root: Path, stacks: Sequence[StackSpec], cdk_apps: Sequence[str]) -> dict[str, str | None]:
    """Build each per-application hook's `files` pattern from the repository's `cdk.json` files.

    A hook listed under a stack's `hook_files` runs when a file of an app changes: the app
    script's folder (every Python file when the app script sits at the tree root) and the named
    files beside each `cdk.json`.

    Args:
        root: The working tree.
        stacks: The repository's stacks.
        cdk_apps: The `cdk.json` paths.

    Returns:
        Hook id to its pattern, or to None when the repository has no app (the hook is dropped).

    """
    patterns: dict[str, str | None] = {}
    for stack in stacks:
        for hook, names in stack.hook_files.items():
            parts = [_app_pattern(root, cdk_json, names) for cdk_json in cdk_apps]
            patterns[hook] = "|".join(parts) if parts else None
    return patterns


def _app_pattern(root: Path, cdk_json: str, names: Sequence[str]) -> str:
    """Build one app's part of a hook's `files` pattern.

    Args:
        root: The working tree.
        cdk_json: The app's `cdk.json`.
        names: The files beside it that also trigger the hook.

    Returns:
        The pattern.

    """
    beside = posixpath.dirname(cdk_json)
    prefix = f"{re.escape(beside)}/" if beside else ""
    alternatives = "|".join(re.escape(name) for name in names)
    folder = _app_folder(root, cdk_json) or "."
    source = r"\.py$" if folder == "." else f"^{re.escape(folder)}/"
    return f"{source}|^{prefix}(?:{alternatives})$"


