def _mapping(value: object, what: str) -> dict[str, object]:
    """Validate a mapping with string keys.

    Args:
        value: The parsed value.
        what: Its name, for the error.

    Returns:
        A plain dict.

    Raises:
        ChecksSpecError: When the value is not a mapping with string keys.

    """
    if not isinstance(value, dict) or not all(isinstance(key, str) for key in value):
        message = f"{what} must be a mapping"
        raise ChecksSpecError(message)
    return {str(key): item for key, item in value.items()}


def _strings(value: object, what: str) -> tuple[str, ...]:
    """Validate a list of strings; a missing value is an empty list.

    Args:
        value: The parsed value.
        what: Its name, for the error.

    Returns:
        The strings.

    Raises:
        ChecksSpecError: When the value is not a list of strings.

    """
    if value is None:
        return ()
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        message = f"{what} must be a list of strings"
        raise ChecksSpecError(message)
    return tuple(str(item) for item in value)


def _string(value: object, what: str) -> str:
    """Validate a non-empty string.

    Args:
        value: The parsed value.
        what: Its name, for the error.

    Returns:
        The string.

    Raises:
        ChecksSpecError: When the value is not a non-empty string.

    """
    if not isinstance(value, str) or not value:
        message = f"{what} must be a non-empty string"
        raise ChecksSpecError(message)
    return value


def _source(folder: Path, relative: object, what: str) -> Path:
    """Resolve a source path of the spec and require the file.

    Args:
        folder: The spec file's folder.
        relative: The path as written in the spec.
        what: Its name, for the error.

    Returns:
        The absolute path.

    Raises:
        ChecksSpecError: When the file does not exist.

    """
    path = (folder / _string(relative, what)).resolve()
    if not path.is_file():
        message = f"{what}: {path} does not exist"
        raise ChecksSpecError(message)
    return path


def _plain(value: object) -> object:
    """Turn ruamel's round-trip containers into plain JSON values.

    Args:
        value: A loaded YAML value.

    Returns:
        The same value as dicts, lists and scalars.

    """
    return json.loads(json.dumps(value))


def _stack_spec(name: str, raw: object, folder: Path) -> StackSpec:
    """Parse one stack's entry.

    Args:
        name: The stack's name.
        raw: Its entry.
        folder: The spec file's folder.

    Returns:
        The stack spec.

    """
    entry = _mapping(raw, f"stacks.{name}")
    files = _mapping(entry.get("files") or {}, f"stacks.{name}.files")
    remove = _mapping(entry.get("remove") or {}, f"stacks.{name}.remove")
    hook_files = _mapping(entry.get("hook_files") or {}, f"stacks.{name}.hook_files")
    pre_commit = entry.get("pre_commit")
    base = entry.get("tsconfig_base")
    return StackSpec(
        name=name,
        files={dest: _source(folder, src, f"stacks.{name}.files.{dest}") for dest, src in files.items()},
        pre_commit=None if pre_commit is None else _source(folder, pre_commit, f"stacks.{name}.pre_commit"),
        pyproject_tables=tuple(
            tuple(table.split(".")) for table in _strings(remove.get("pyproject_tables"), "pyproject_tables")
        ),
        setup_cfg_sections=_strings(remove.get("setup_cfg_sections"), "setup_cfg_sections"),
        remove_files=_strings(remove.get("files"), "remove.files"),
        hook_files={hook: _strings(names, f"hook_files.{hook}") for hook, names in hook_files.items()},
        tsconfig_base=None if base is None else _string(base, f"stacks.{name}.tsconfig_base"),
        eslint_imports=_strings(entry.get("eslint_imports"), "eslint_imports"),
        node_dev_dependencies=_strings(entry.get("node_dev_dependencies"), "node_dev_dependencies"),
    )


def _round_trip_yaml() -> YAML:
    """Build the YAML reader and writer used for every YAML file checks-sync touches.

    Returns:
        A round-trip YAML instance in the pre-commit layout (sequences indented under their key).

    """
    yaml = YAML()
    yaml.preserve_quotes = True
    yaml.width = 4096
    yaml.indent(mapping=2, sequence=4, offset=2)
    return yaml


def load_spec(spec_file: Path) -> ChecksSpec:
    """Read and validate the spec file.

    Args:
        spec_file: The spec's path.

    Returns:
        The spec.

    Raises:
        ChecksSpecError: When the file is missing, malformed, or names a source that does not exist.

    """
    try:
        loaded: object = _plain(_round_trip_yaml().load(spec_file.read_text(encoding="utf-8")))
    except (OSError, YAMLError) as error:
        message = f"reading the checks spec {spec_file} failed: {error}"
        raise ChecksSpecError(message) from error
    raw = _mapping(loaded, str(spec_file))
    folder = spec_file.parent
    pins = _mapping(raw.get("pins"), "pins")
    supersedes = _mapping(raw.get("supersedes") or {}, "supersedes")
    stacks = _mapping(raw.get("stacks"), "stacks")
    return ChecksSpec(
        source=spec_file,
        pins=pins,
        common_pre_commit=_source(folder, _mapping(raw.get("common"), "common").get("pre_commit"), "common"),
        stacks={name: _stack_spec(name, entry, folder) for name, entry in stacks.items()},
        supersede_repos=frozenset(_strings(supersedes.get("repos"), "supersedes.repos")),
        supersede_tools=frozenset(_strings(supersedes.get("local_entry_tools"), "supersedes.local_entry_tools")),
        lint_task=_string(raw.get("lint_task"), "lint_task"),
        pre_commit_pin=_string(pins.get("pre-commit"), "pins.pre-commit"),
    )


