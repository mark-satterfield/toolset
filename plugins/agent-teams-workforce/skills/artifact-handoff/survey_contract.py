def _parse_evidence_ref(value: object, path: str) -> EvidenceRef:
    raw: dict[str, object] = _mapping(value, path, EVIDENCE_REF_REQUIRED_KEYS, EVIDENCE_REF_KEYS)
    result: EvidenceRef = {
        "path": _string(raw, path, "path", 0),
        "heading": _string(raw, path, "heading", 0),
        "repo": _string(raw, path, "repo", 0),
        "revision": _string(raw, path, "revision", 0),
        "url": _string(raw, path, "url", 0),
    }
