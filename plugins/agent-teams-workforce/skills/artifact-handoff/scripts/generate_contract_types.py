"""Generate the typed Python modules of artifact-handoff contracts from their JSON Schemas.

Each schema under ``schemas/`` is the one definition of its contract. This script writes the typed
Python view mypy needs (Literal aliases, TypedDicts, key and value constants, builders and a
stdlib-only parser) next to it in ``scripts/``. Run ``python3 scripts/generate_contract_types.py``
after changing a schema; ``check_contract_types.py`` (or ``--check`` here) exits 1 when a generated
module differs from what its schema produces.

Only naming lives here (which constant or alias each schema element becomes); every key and allowed
value is read from the schema.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from collections.abc import (
    Callable,  # ruff: ignore[typing-only-standard-library-import] - get_type_hints resolves Target.render at runtime.
)
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Final, TypeIs

if TYPE_CHECKING:
    from collections.abc import Sequence

type Json = bool | int | float | str | list[Json] | dict[str, Json] | None
type JsonObject = dict[str, Json]

SKILL_DIR: Final[Path] = Path(__file__).resolve().parents[1]
SCHEMA_DIR: Final[Path] = SKILL_DIR / "schemas"
SCRIPT_DIR: Final[Path] = SKILL_DIR / "scripts"
IDENTIFIER: Final[re.Pattern[str]] = re.compile(r"[^A-Za-z0-9]+")


class SchemaShapeError(ValueError):
    """A schema uses a shape this generator does not translate."""


@dataclass(frozen=True)
class Target:
    """One generated module: the schema it comes from, the file it writes and its renderer."""

    schema: Path
    output: Path
    render: Callable[[JsonObject, str], str]


def _is_object(value: Json) -> TypeIs[JsonObject]:
    return isinstance(value, dict)


def _obj(value: Json, where: str) -> JsonObject:
    if not _is_object(value):
        message: str = f"{where}: expected a JSON object"
        raise SchemaShapeError(message)
    return value


def _text(value: Json, where: str) -> str:
    if not isinstance(value, str):
        message: str = f"{where}: expected a string"
        raise SchemaShapeError(message)
    return value


def _texts(value: Json, where: str) -> list[str]:
    if not isinstance(value, list):
        message: str = f"{where}: expected an array"
        raise SchemaShapeError(message)
    return [_text(item, f"{where}[{index}]") for index, item in enumerate(value)]


def _closed(schema: JsonObject, where: str) -> tuple[JsonObject, list[str]]:
    """Return the properties of a closed object schema whose every property is required.

    Args:
        schema: The object schema.
        where: Its location, for error messages.

    Returns:
        The properties and their keys in schema order.

    Raises:
        SchemaShapeError: The schema is not a closed object with every property required.

    """
    if schema.get("type") != "object" or schema.get("additionalProperties") is not False:
        message: str = f"{where}: expected an object with additionalProperties false"
        raise SchemaShapeError(message)
    properties: JsonObject = _obj(schema.get("properties"), f"{where}.properties")
    required: list[str] = _texts(schema.get("required"), f"{where}.required")
    if sorted(required) != sorted(properties):
        message = f"{where}: every property must be required"
        raise SchemaShapeError(message)
    return properties, list(properties)


def _expect_type(schema: JsonObject, kind: str, where: str) -> None:
    if schema.get("type") != kind:
        message: str = f"{where}: expected type {kind}"
        raise SchemaShapeError(message)


def _constant(prefix: str, value: str) -> str:
    return prefix + IDENTIFIER.sub("_", value).strip("_").upper()


def _field_name(key: str) -> str:
    return "FIELD_" + re.sub(r"(?<!^)(?=[A-Z])", "_", key).upper()


def schema_sha256(path: Path) -> str:
    """Hash a schema file's bytes.

    Args:
        path: The schema file.

    Returns:
        The lower-case hex SHA-256 of the file.

    """
    return hashlib.sha256(path.read_bytes()).hexdigest()


TASK_DEPS_TEMPLATE: Final[str] = '''"""Cross-Story Task dependencies: the task-deps contract.

GENERATED by scripts/generate_contract_types.py from schemas/task-deps.schema.json. Never edit this
file: change the schema and run ``python3 scripts/generate_contract_types.py``;
``scripts/check_contract_types.py`` fails when this module is stale.
"""

from pathlib import Path
from typing import Final, Literal, TypedDict, TypeIs

type JsonValue = bool | int | float | str | list[JsonValue] | dict[str, JsonValue] | None

TASK_DEPS_SCHEMA_PATH: Final[Path] = Path(__file__).resolve().parents[1] / "schemas" / "task-deps.schema.json"
SCHEMA_SHA256: Final[str] = "@SHA@"

type TaskDepsEdgeKind = @KIND_LITERAL@

@KIND_CONSTANTS@
TASK_DEPS_EDGE_KINDS: Final[frozenset[TaskDepsEdgeKind]] = frozenset(
    (
@KIND_NAMES@
    ),
)

@FIELD_CONSTANTS@

TaskDepsEdge = TypedDict(
    "TaskDepsEdge",
    {@EDGE_FIELDS@},
)


class TaskDeps(TypedDict):
    """@DOC_SUMMARY@"""

@DOC_FIELDS@


class TaskDepsError(ValueError):
    """A document does not conform to the task-deps schema."""


_DOC_KEYS: Final[frozenset[str]] = frozenset((@DOC_KEYS@))
_EDGE_KEYS: Final[frozenset[str]] = frozenset((@EDGE_KEYS@))


def _is_object(value: object) -> TypeIs[dict[str, object]]:
    return isinstance(value, dict) and all(isinstance(key, str) for key in value)


def _is_kind(value: object) -> TypeIs[TaskDepsEdgeKind]:
    return isinstance(value, str) and value in TASK_DEPS_EDGE_KINDS


def task_deps_edge(frm: str, to: str, kind: TaskDepsEdgeKind, reason: str) -> TaskDepsEdge:
    """Build one edge.

    Args:
        frm: The prerequisite Task key.
        to: The dependent Task key.
        kind: The edge kind.
        reason: A one-line justification.

    Returns:
        The edge.

    Raises:
        TypeError: A key or the reason is not a string.
        TaskDepsError: kind is not an allowed kind.

    """
    if not isinstance(frm, str) or not isinstance(to, str) or not isinstance(reason, str):
        message: str = "from, to and reason must be str"
        raise TypeError(message)
    if not _is_kind(kind):
        message = f"kind {kind!r} is not one of {sorted(TASK_DEPS_EDGE_KINDS)}"
        raise TaskDepsError(message)
    return {FIELD_FROM: frm, FIELD_TO: to, FIELD_KIND: kind, FIELD_REASON: reason}


def empty_task_deps() -> TaskDeps:
    """Build the document written for a single-repository span.

    Returns:
        @EMPTY_DOC@

    """
    return {@EMPTY@}


def _parse_edge(value: object, where: str) -> TaskDepsEdge:
    if not _is_object(value):
        message: str = f"{where}: expected an object"
        raise TaskDepsError(message)
    if set(value) != _EDGE_KEYS:
        message = f"{where}: keys must be exactly {sorted(_EDGE_KEYS)}, got {sorted(value)}"
        raise TaskDepsError(message)
    frm: object = value[FIELD_FROM]
    to: object = value[FIELD_TO]
    kind: object = value[FIELD_KIND]
    reason: object = value[FIELD_REASON]
    if not isinstance(frm, str) or not isinstance(to, str) or not isinstance(reason, str):
        message = f"{where}: {FIELD_FROM}, {FIELD_TO} and {FIELD_REASON} must be strings"
        raise TaskDepsError(message)
    if not _is_kind(kind):
        message = f"{where}.{FIELD_KIND}: {kind!r} is not one of {sorted(TASK_DEPS_EDGE_KINDS)}"
        raise TaskDepsError(message)
    return {FIELD_FROM: frm, FIELD_TO: to, FIELD_KIND: kind, FIELD_REASON: reason}


def parse_task_deps(value: object) -> TaskDeps:
    """Validate a loaded task-deps document against the schema and narrow it.

    Args:
        value: The decoded JSON document.

    Returns:
        The typed document.

    Raises:
        TaskDepsError: The document does not conform to the schema; the message names the field.

    """
    if not _is_object(value):
        message: str = "task-deps: expected an object"
        raise TaskDepsError(message)
    if set(value) != _DOC_KEYS:
        message = f"task-deps: keys must be exactly {sorted(_DOC_KEYS)}, got {sorted(value)}"
        raise TaskDepsError(message)
    edges: object = value[FIELD_EDGES]
    acyclic: object = value[FIELD_ACYCLIC]
    cycle: object = value[FIELD_CYCLE]
    if not isinstance(edges, list):
        message = f"task-deps.{FIELD_EDGES}: expected an array"
        raise TaskDepsError(message)
    if not isinstance(acyclic, bool):
        message = f"task-deps.{FIELD_ACYCLIC}: expected a boolean"
        raise TaskDepsError(message)
    if not isinstance(cycle, list) or not all(isinstance(key, str) for key in cycle):
        message = f"task-deps.{FIELD_CYCLE}: expected an array of strings"
        raise TaskDepsError(message)
    parsed: list[TaskDepsEdge] = [
        _parse_edge(edge, f"task-deps.{FIELD_EDGES}[{index}]") for index, edge in enumerate(edges)
    ]
    keys: list[str] = [key for key in cycle if isinstance(key, str)]
    return {FIELD_EDGES: parsed, FIELD_ACYCLIC: acyclic, FIELD_CYCLE: keys}
'''


def _literal(values: Sequence[str]) -> str:
    return "Literal[" + ", ".join(json.dumps(value) for value in values) + "]"


@dataclass(frozen=True)
class TaskDepsModel:
    """The translated task-deps schema."""

    doc_keys: tuple[str, str, str]
    edge_keys: tuple[str, str, str, str]
    kinds: tuple[str, ...]
    empty: JsonObject
    summary: str


def _task_deps_model(schema: JsonObject) -> TaskDepsModel:
    """Translate the task-deps schema into the shape the template types.

    Args:
        schema: The decoded task-deps schema.

    Returns:
        The document keys (edges, acyclic, cycle), the edge keys (from, to, kind, reason), the
        allowed kinds and the empty document.

    Raises:
        SchemaShapeError: The schema uses a shape this generator does not translate.

    """
    properties, doc_keys = _closed(schema, "task-deps")
    match doc_keys:
        case [edges_key, acyclic_key, cycle_key]:
            pass
        case _:
            message: str = "task-deps: expected the three properties edges, acyclic, cycle"
            raise SchemaShapeError(message)
    edges: JsonObject = _obj(properties[edges_key], f"properties.{edges_key}")
    _expect_type(edges, "array", f"properties.{edges_key}")
    _expect_type(_obj(properties[acyclic_key], f"properties.{acyclic_key}"), "boolean", acyclic_key)
    cycle: JsonObject = _obj(properties[cycle_key], f"properties.{cycle_key}")
    _expect_type(cycle, "array", cycle_key)
    _expect_type(_obj(cycle.get("items"), f"{cycle_key}.items"), "string", f"{cycle_key}.items")
    edge_keys, kinds = _edge_shape(_obj(edges.get("items"), f"{edges_key}.items"))
    empty: JsonObject = _obj(schema.get("x-empty"), "x-empty")
    if list(empty) != doc_keys:
        message = "x-empty: must name every property in schema order"
        raise SchemaShapeError(message)
    return TaskDepsModel(
        doc_keys=(edges_key, acyclic_key, cycle_key),
        edge_keys=edge_keys,
        kinds=kinds,
        empty=empty,
        summary=_text(schema.get("description"), "description").partition(": ")[0].rstrip(".") + ".",
    )


def _edge_shape(items: JsonObject) -> tuple[tuple[str, str, str, str], tuple[str, ...]]:
    """Translate the edge item schema.

    Args:
        items: The ``edges.items`` schema.

    Returns:
        The edge keys (from, to, kind, reason) and the allowed kinds.

    Raises:
        SchemaShapeError: The edge schema uses a shape this generator does not translate.

    """
    edge_props, edge_keys = _closed(items, "edges.items")
    match edge_keys:
        case [from_key, to_key, kind_key, reason_key]:
            pass
        case _:
            message: str = "task-deps edge: expected the four properties from, to, kind, reason"
            raise SchemaShapeError(message)
    for key in (from_key, to_key, reason_key):
        _expect_type(_obj(edge_props[key], f"edge.{key}"), "string", f"edge.{key}")
    kind_schema: JsonObject = _obj(edge_props[kind_key], f"edge.{kind_key}")
    kinds: list[str] = _texts(kind_schema.get("enum"), f"edge.{kind_key}.enum")
    return (from_key, to_key, kind_key, reason_key), tuple(kinds)


def render_task_deps(schema: JsonObject, sha: str) -> str:
    """Render ``task_deps_contract.py`` from the task-deps schema.

    Args:
        schema: The decoded task-deps schema.
        sha: The SHA-256 of the schema file.

    Returns:
        The module source.

    """
    model: TaskDepsModel = _task_deps_model(schema)
    edge: tuple[str, str, str, str] = model.edge_keys
    doc: tuple[str, str, str] = model.doc_keys
    kind_names: list[str] = [_constant("KIND_", kind) for kind in model.kinds]
    edge_types: tuple[str, str, str, str] = ("str", "str", "TaskDepsEdgeKind", "str")
    doc_types: tuple[str, str, str] = ("list[TaskDepsEdge]", "bool", "list[str]")
    replacements: dict[str, str] = {
        "@SHA@": sha,
        "@KIND_LITERAL@": _literal(model.kinds),
        "@KIND_CONSTANTS@": "\n".join(
            f'{name}: Final = "{kind}"' for name, kind in zip(kind_names, model.kinds, strict=True)
        ),
        "@KIND_NAMES@": "\n".join(f"        {name}," for name in kind_names),
        "@FIELD_CONSTANTS@": "\n".join(f'{_field_name(key)}: Final = "{key}"' for key in (*doc, *edge)),
        "@EDGE_FIELDS@": ", ".join(f'"{key}": {kind}' for key, kind in zip(edge, edge_types, strict=True)),
        "@DOC_FIELDS@": "\n".join(f"    {key}: {kind}" for key, kind in zip(doc, doc_types, strict=True)),
        "@DOC_SUMMARY@": model.summary,
        "@DOC_KEYS@": ", ".join(_field_name(key) for key in doc),
        "@EDGE_KEYS@": ", ".join(_field_name(key) for key in edge),
        "@EMPTY_DOC@": "The document " + json.dumps(model.empty) + ".",
        "@EMPTY@": ", ".join(f"{_field_name(key)}: {value!r}" for key, value in model.empty.items()),
    }
    text: str = TASK_DEPS_TEMPLATE
    for marker, value in replacements.items():
        text = text.replace(marker, value)
    return text


TARGETS: Final[dict[str, Target]] = {
    "task-deps": Target(
        schema=SCHEMA_DIR / "task-deps.schema.json",
        output=SCRIPT_DIR / "task_deps_contract.py",
        render=render_task_deps,
    ),
}


def load_schema(path: Path) -> JsonObject:
    """Read one schema file.

    Args:
        path: The schema file.

    Returns:
        The decoded schema.

    Raises:
        SchemaShapeError: The file is not a JSON object.

    """
    value: Json = json.loads(path.read_text(encoding="utf-8"))
    if not _is_object(value):
        message: str = f"{path}: expected a JSON object"
        raise SchemaShapeError(message)
    return value


def render(target: Target) -> str:
    """Render one target's module from its schema as it is now.

    Args:
        target: The generated module.

    Returns:
        The module source.

    """
    return target.render(load_schema(target.schema), schema_sha256(target.schema))


def stale() -> list[Path]:
    """List the generated modules that differ from what their schemas produce.

    Returns:
        The stale output files, in target order.

    """
    found: list[Path] = []
    for target in TARGETS.values():
        current: str = target.output.read_text(encoding="utf-8") if target.output.is_file() else ""
        if current != render(target):
            found.append(target.output)
    return found


def main(argv: Sequence[str]) -> int:
    """Write every generated module, or with ``--check`` report the stale ones.

    Args:
        argv: The command-line arguments after the program name.

    Returns:
        0 when written or current; 1 when ``--check`` finds a stale module.

    Raises:
        ValueError: An argument other than ``--check`` was given.

    """
    if list(argv) not in ([], ["--check"]):
        message: str = f"usage: generate_contract_types.py [--check], got {list(argv)}"
        raise ValueError(message)
    if argv:
        outdated: list[Path] = stale()
        for path in outdated:
            sys.stderr.write(f"stale generated contract module: {path}\n")
        return 1 if outdated else 0
    for target in TARGETS.values():
        text: str = render(target)
        current: str = target.output.read_text(encoding="utf-8") if target.output.is_file() else ""
        if current != text:
            target.output.write_text(text, encoding="utf-8")
        sys.stdout.write(f"wrote {target.output}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
