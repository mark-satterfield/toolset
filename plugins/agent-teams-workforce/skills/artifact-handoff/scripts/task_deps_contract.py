class TaskDeps(TypedDict):
    """Cross-Story Task dependencies for a multi-repository span."""

    edges: list[TaskDepsEdge]
    acyclic: bool
    cycle: list[str]


class TaskDepsError(ValueError):
    """A document does not conform to the task-deps schema."""


_DOC_KEYS: Final[frozenset[str]] = frozenset((FIELD_EDGES, FIELD_ACYCLIC, FIELD_CYCLE))
_EDGE_KEYS: Final[frozenset[str]] = frozenset((FIELD_FROM, FIELD_TO, FIELD_KIND, FIELD_REASON))


def _is_object(value: object) -> TypeIs[dict[str, object]]:
    return isinstance(value, dict) and all(isinstance(key, str) for key in value)


def _is_kind(value: object) -> TypeIs[TaskDepsEdgeKind]:
    return isinstance(value, str) and value in TASK_DEPS_EDGE_KINDS


def _member(value: JsonValue, key: str) -> dict[str, JsonValue]:
    if not isinstance(value, dict):
        message: str = f"task-deps schema: expected an object holding {key!r}"
        raise TypeError(message)
    child: JsonValue = value.get(key)
    if not isinstance(child, dict):
        message = f"task-deps schema: {key!r} is not an object"
        raise TypeError(message)
    return child


